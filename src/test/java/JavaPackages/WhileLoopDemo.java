package JavaPackages;

public class WhileLoopDemo {

    public static void main(String[] args) {

        int i = 1;
        while(i<=10){
            System.out.println("Value of i: " + i);
            i++;

        }

        int j =10;
        while(j>=0){
            System.out.println("Value of j: " + j);
            j--;
        }



    //do while loop

    int k = 20;
    do{
        System.out.println("Value of k: " + k);
        k++;
    }while(k<30);
}


}
